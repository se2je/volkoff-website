import React from 'react';

// Пиксельные рожицы настроения корзины, 9×9.
// '#' — чёрный пиксель, '.' — белый (глаза/рот), '_' — прозрачный.
const FACES: Record<string, string[]> = {
    // злится — пустая корзина
    empty: ['#########', '#.#####.#', '##.###.##', '##.###.##', '#########', '###...###', '##.###.##', '#########', '#########'],
    // «и это всё?» — бровь вверх, рот ровный
    tiny: ['#########', '#..######', '#####..##', '##.###.##', '#########', '#########', '###....##', '#########', '#########'],
    // уже лучше — улыбка
    ok: ['#########', '#########', '##.###.##', '##.###.##', '#########', '#.#####.#', '##.....##', '#########', '#########'],
    // вкус есть — прищур и ухмылка
    taste: ['#########', '#########', '##..#..##', '#########', '#########', '######.##', '##.....##', '#########', '#########'],
    // богато — глаза-нолики, рот «о»
    rich: ['#########', '#..###..#', '#..###..#', '#########', '#########', '###...###', '###...###', '#########', '#########'],
    // горишь — глаза-звёзды
    fire: ['#########', '#.#.#.#.#', '##.###.##', '#.#.#.#.#', '#########', '##.....##', '###...###', '#########', '#########'],
    // король улиц — корона
    king: ['#_#_#_#_#', '#########', '#########', '##.###.##', '#########', '#.#####.#', '##.....##', '#########', '#########'],
    // убил — череп
    dead: ['_#######_', '#########', '#.#.#.#.#', '##.###.##', '#.#.#.#.#', '#########', '##.#.#.##', '_#######_', '__#####__'],
};

interface Props {
    mood: string;
    size?: number;
    title?: string;
}

const MoodFace: React.FC<Props> = ({ mood, size = 18, title }) => {
    const rows = FACES[mood] ?? FACES.empty;
    const rects: React.ReactNode[] = [];
    rows.forEach((row, y) =>
        [...row].forEach((c, x) => {
            if (c === '_') return;
            rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1.02} height={1.02} fill={c === '#' ? '#0b0b0b' : '#ffffff'} />);
        }),
    );
    return (
        <svg
            viewBox="0 0 9 9"
            width={size}
            height={size}
            shapeRendering="crispEdges"
            role="img"
            aria-label={title}
            style={{ display: 'block', flex: `0 0 ${size}px` }}
        >
            {title && <title>{title}</title>}
            {rects}
        </svg>
    );
};

export default MoodFace;
